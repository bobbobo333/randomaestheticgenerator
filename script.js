/* =========================
   ACCESSORIES
========================= */

function generateAccessories() {

    const button =
        document.getElementById(
            "accessoryButton"
        );

    button.disabled = true;


    const countResult =
        document.getElementById(
            "accessoryCount"
        );


    const roll =
        Math.random();


    let count;


    if (roll < 0.25) {

        count = 1;

    } else if (roll < 0.70) {

        count = 2;

    } else if (roll < 0.93) {

        count = 3;

    } else {

        count = 4;
    }


    rollResult(
        countResult,
        count +
        " ACCESSOR" +
        (count > 1 ? "IES" : "Y"),
        function () {

            generateAccessoryResults(
                count
            );

        }
    );
}


function generateAccessoryResults(
    count
) {

    const container =
        document.getElementById(
            "accessories"
        );

    container.innerHTML = "";


    const usedItems = [];


    for (
        let i = 0;
        i < count;
        i++
    ) {

        const box =
            document.createElement("div");


        box.className =
            "sub-result";


        box.innerHTML =
            "<strong>" +
            "Accessory " +
            (i + 1) +
            "</strong>" +
            "Rolling...";


        container.appendChild(box);


        setTimeout(function () {

            let aesthetic;
            let item;
            let attempts = 0;


            do {

                aesthetic =
                    randomAesthetic(
                        accessories
                    );

                item =
                    randomItem(
                        accessories,
                        aesthetic
                    );

                attempts++;

            } while (
                usedItems.includes(item) &&
                attempts < 20
            );


            usedItems.push(item);


            rollResult(
                box,
                aesthetic +
                " → " +
                item
            );


        }, i * 300);

    }


    document.getElementById(
        "accessoryButton"
    ).textContent =
        "ACCESSORIES LOCKED";
}


