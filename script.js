function generateHat() {

    const button =
        document.getElementById("hatButton");

    button.disabled = true;

    const result =
        document.getElementById("hat");


    const noHat =
        Math.random() < 0.20;


    let finalResult;


    if (noHat) {

        finalResult = "NO HAT";

    } else {

        const aesthetic =
            randomAesthetic(hats);

        const item =
            randomItem(hats, aesthetic);

        finalResult =
            aesthetic + " → " + item;
    }


    rollResult(
        result,
        finalResult,
        function () {

            button.textContent =
                "HAT LOCKED";

        }
    );
}


