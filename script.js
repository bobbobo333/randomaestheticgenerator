function generateLayers() {

    const button =
        document.getElementById("layerButton");

    button.disabled = true;


    const countResult =
        document.getElementById("layerCount");


    const roll =
        Math.random();


    let layerCount;


    /* 15% NO LAYERS */

    if (roll < 0.15) {

        rollResult(
            countResult,
            "NO LAYERS",
            function () {

                button.textContent =
                    "LAYERS LOCKED";

            }
        );

        return;
    }


    /* Remaining 85% */

    if (roll < 0.60) {

        layerCount = 1;

    } else if (roll < 0.90) {

        layerCount = 2;

    } else {

        layerCount = 3;
    }


    rollResult(
        countResult,
        layerCount +
        " LAYER" +
        (layerCount > 1 ? "S" : ""),
        function () {

            generateUpperLayerResults(
                layerCount
            );

        }
    );
}


function generateUpperLayerResults(layerCount) {

    const container =
        document.getElementById("layers");

    container.innerHTML = "";


    const layerNames = [];


    if (layerCount === 1) {

        layerNames.push("Base Layer");

    }


    if (layerCount === 2) {

        layerNames.push("Base Layer");
        layerNames.push("Outer Layer");

    }


    if (layerCount === 3) {

        layerNames.push("Base Layer");
        layerNames.push("Middle Layer");
        layerNames.push("Outer Layer");

    }


    layerNames.forEach(function (
        layerName,
        index
    ) {

        const box =
            document.createElement("div");

        box.className =
            "sub-result";


        box.innerHTML =
            "<strong>" +
            layerName +
            "</strong>" +
            "Rolling...";


        container.appendChild(box);


        setTimeout(function () {

            let database;


            if (
                layerName === "Base Layer"
            ) {

                database = upperBase;

            } else if (
                layerName === "Middle Layer"
            ) {

                database = upperMiddle;

            } else {

                database = upperOuter;
            }


            let finalResult;


            /* Outer layer can disappear */

            if (
                layerName === "Outer Layer" &&
                Math.random() < 0.25
            ) {

                finalResult =
                    "NO OUTER LAYER";

            } else {

                const aesthetic =
                    randomAesthetic(database);

                const item =
                    randomItem(
                        database,
                        aesthetic
                    );

                finalResult =
                    aesthetic +
                    " → " +
                    item;
            }


            rollResult(
                box,
                finalResult
            );


        }, index * 300);

    });


    document.getElementById(
        "layerButton"
    ).textContent =
        "LAYERS LOCKED";
}


